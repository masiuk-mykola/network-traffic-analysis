// Refreshes the generated API types and zod schemas before the dev server starts.
// Prefers the running API (its document is the truth), falls back to the copy in the repo.
import { spawnSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = dirname(dirname(fileURLToPath(import.meta.url)))
const bin = (name) => join(ROOT, 'node_modules', '.bin', name)

const FALLBACK = '../backend/openapi.json'
const PROBE_TIMEOUT_MS = 2_000
const ROUTES_OUT = join(ROOT, 'src', 'lib', 'api', 'generated', 'routes.gen.ts')

async function liveDocument() {
  const base = (process.env.CAPTURE_API_URL ?? 'http://localhost:8700').replace(/\/+$/, '')
  const url = `${base}/openapi.json`
  try {
    const res = await fetch(url, { signal: AbortSignal.timeout(PROBE_TIMEOUT_MS) })
    return res.ok ? url : null
  } catch {
    return null
  }
}

/**
 * The document's path templates, as a runtime array.
 *
 * The API opens a `Retry-After` window on the route template rather than on the address that was
 * refused, so the client has to know which template an address belongs to. Taking the list from the
 * contract rather than writing a matcher by hand means a new endpoint is covered the day it appears.
 */
async function writeRouteTemplates(input) {
  const document = input.startsWith('http')
    ? await (await fetch(input, { signal: AbortSignal.timeout(PROBE_TIMEOUT_MS) })).json()
    : JSON.parse(readFileSync(join(ROOT, input), 'utf8'))

  const templates = Object.keys(document.paths ?? {}).sort()
  if (templates.length === 0) throw new Error('the document describes no paths')

  writeFileSync(
    ROUTES_OUT,
    [
      '// This file is auto-generated by scripts/sync-api-schema.mjs. Do not edit.',
      '',
      '/** Every path the API document describes, as the template the server keys its limits by. */',
      'export const ROUTE_TEMPLATES = [',
      ...templates.map((template) => `  '${template}',`),
      '] as const',
      '',
    ].join('\n'),
  )
  return templates.length
}

function generate(input) {
  const steps = [
    ['openapi-typescript', [input, '-o', 'src/lib/api/schema.d.ts']],
    ['openapi-ts', ['-i', input]],
  ]
  for (const [name, args] of steps) {
    const run = spawnSync(bin(name), args, { stdio: 'inherit', cwd: ROOT })
    if (run.error) console.error(`api-schema: ${name} failed to start — ${run.error.message}`)
    if (run.status !== 0) return false
  }
  return true
}

const input = (await liveDocument()) ?? FALLBACK

if (input === FALLBACK && !existsSync(FALLBACK)) {
  console.error(`api-schema: the API is not running and ${FALLBACK} is missing — skipping.`)
  process.exit(0)
}

console.log(`api-schema: generating from ${input}`)
if (!generate(input)) {
  // A stale schema must not block the dev server; the committed files still work.
  console.error('api-schema: generation failed, keeping the committed files.')
}

try {
  console.log(`api-schema: ${await writeRouteTemplates(input)} route templates`)
} catch (error) {
  console.error(
    `api-schema: route templates failed — ${error.message}, keeping the committed file.`,
  )
}
